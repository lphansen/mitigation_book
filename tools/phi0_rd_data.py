#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Write the data of Tables 38 to 40 for the interactive figure of Online Appendix N.

The tables come from the paper tex through tools/sync_tables_from_tex.py, which
writes docs/_static/table/table38_*.md to table40_*.md. This script reads those
three markdown tables and writes docs/_static/phi0_rd_data.js, which defines the
global PHI0_RD_DATA used by docs/_static/phi0_rd_interactive.html. Run it after
sync_tables_from_tex.py whenever the tables change.

Usage:
    python tools/phi0_rd_data.py            # (re)write the data file
    python tools/phi0_rd_data.py --check    # report only, exit 1 if stale
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE_DIR = os.path.join(REPO, "docs", "_static", "table")
OUT = os.path.join(REPO, "docs", "_static", "phi0_rd_data.js")

# paper table, file and xi_m value (100000 stands for infinity, as in the code)
TABLES = [
    (38, "table38_phi0_psi0_chi_xi_inf.md", "inf"),
    (39, "table39_phi0_psi0_chi_xi_01.md", "0.1"),
    (40, "table40_phi0_psi0_chi_xi_005.md", "0.05"),
]
# table columns after phi_0, psi_0 and chi, in paper order
OUTCOMES = ["emissions", "R&D investment", "technology-first probability",
            "conditional tech-jump median year"]


def read_rows(path):
    """Read the data rows of one generated markdown table.

    Parameters
    ----------
    path : str
        A docs/_static/table/*.md file of Tables 38 to 40.

    Returns
    -------
    list of list of float
        One list per table row: phi_0, psi_0, chi and the four outcomes.
    """
    rows = []
    for line in open(path, encoding="utf-8"):
        # data rows start with "| " and a number; the header and rule rows do not
        cells = [c.strip().strip("$") for c in line.strip().strip("|").split("|")]
        if len(cells) == 3 + len(OUTCOMES) and cells[0][:1].isdigit():
            rows.append([float(c) for c in cells])
    if len(rows) != 27:
        sys.stderr.write("ABORT: %s has %d data rows (expected 27)\n" % (path, len(rows)))
        sys.exit(2)
    return rows


def build():
    """Return the JavaScript text of the data file."""
    data = {"outcomes": OUTCOMES, "xi_m": [], "rows": []}
    for number, name, xi_m in TABLES:
        data["xi_m"].append({"value": xi_m, "table": number})
        for phi_0, psi_0, chi, *outcomes in read_rows(os.path.join(TABLE_DIR, name)):
            data["rows"].append({"xi_m": xi_m, "phi_0": phi_0, "psi_0": psi_0,
                                 "chi": chi, "values": outcomes})
    return ("// Generated by tools/phi0_rd_data.py from Tables 38 to 40. Do not edit.\n"
            "const PHI0_RD_DATA = %s;\n" % json.dumps(data))


def main():
    text = build()
    current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if "--check" in sys.argv:
        sys.stdout.write("[up-to-date]\n" if current == text else "[STALE] %s\n" % OUT)
        sys.exit(0 if current == text else 1)
    if current != text:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        sys.stdout.write("[written] %s\n" % OUT)
    else:
        sys.stdout.write("[up-to-date] %s\n" % OUT)


if __name__ == "__main__":
    main()
